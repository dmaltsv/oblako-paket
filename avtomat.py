def do_job(actor: dict, one: dict, job: dict, env: dict, args) -> dict:
    """Работа целиком. Всё, что здесь падает, становится отчётом «не вышло»."""
    folder = work_folder(job, one)
    got = recording(job, one, env)
    text = transcribe(got, folder, env)
    done = to_library(text, one, job, signature(actor, one), env,
                      getattr(args, "repo", None))
    done.update(measure(folder))
    done["outcome"] = client.TRANSCRIPT_DONE
    done["names_stitched"] = bool(got.get("transcript"))
    return done


def signature(actor: dict, one: dict) -> str:
    """Чьим именем подписан коммит: «Автомат: <Имя>» — хозяина ключа.

    Имя приезжает из шапки ответа сервера, а не из настроек машины: в истории
    Библиотеки видно, ЧЕЙ автомат писал, а ключ у автомата личный. Хозяин не
    назвался — подписываемся организатором встречи: пустая подпись превратила бы
    коммит автомата в коммит человека (инвариант 23).
    """
    organizer = one.get("organizer") or {}
    return (str((actor or {}).get("name") or organizer.get("name") or "").strip()
            or "Автомат")


def guard_word(env: dict) -> None:
    """Шаг 0: хук стража слова в `~/.claude/settings.json` облачной машины.

    ТОЛЬКО В ОБЛАКЕ. На компьютере домашний файл настроек — общий на все
    проекты человека, и хук туда кладёт `install_skills.py --home` по его
    выбору, а не пробный запуск автомата молча.

    Беда здесь печатается и не останавливает запуск: отчёт серверу обязан уйти
    при любом исходе, а расшифровке страж не нужен. Чужой файл настроек, который
    не разобрать, не переписывается — `install_hook` откажет словами.
    """
    if not strazh.in_cloud():
        return
    target = strazh.settings_file(Path.home())
    try:
        done = strazh.install_hook(target)
    except client.ClientError as beda:
        say(f"Страж слова не поставлен: {beda.message}", env, stream=sys.stderr)
        for line in beda.details:
            say(f"  · {line}", env, stream=sys.stderr)
        return
    except OSError as beda:
        say(f"Страж слова не поставлен: {target}: {beda}", env, stream=sys.stderr)
        return
    say(f"Страж слова {strazh.HOOK_STATE_WORDS[done]}: {target}", env)


def cmd_run(args, env: dict) -> int:
    """Один запуск автомата: работа задания и отчёт при ЛЮБОМ её исходе.

    Состав работы — из задания (`work_of`). Разбор идёт только за СДЕЛАННОЙ
    расшифровкой: «записи ещё нет» вернёт задание в очередь вместе с разбором, а
    отчёт «разбор не вышел» поверх «расшифровка не вышла» был бы вторым письмом
    человеку об одной беде.
    """
    guard_word(env)
    key = client.access_key(env)
    url = client.base_url(env)
    actor, found = awaiting_jobs(url, key)
    one, job = job_of(found, args.job)
    say(f"Задание {job['id']}: «{title_of(one)}» {one.get('date')} "
        f"{one.get('start_time') or ''}".rstrip(), env)
    try:
        work = work_of(job)
    except Stop as beda:
        say(beda.message, env, stream=sys.stderr)
        return transcript_report(one, job, {"outcome": beda.outcome, "error": beda.code},
                                 env, url, key)
    if work != REVIEW_WORK:
        code = transcript_job(actor, one, job, env, args, url, key)
        if code != client.EXIT_OK or work == TRANSCRIPT_WORK:
            return code
    return review_job(one, job, env, url, key)


def transcript_job(actor: dict, one: dict, job: dict, env: dict, args,
                   url: str, key: str) -> int:
    """Расшифровка и отчёт о ней при ЛЮБОМ исходе. Код — как у `run`."""
    # ЧЕЛОВЕКУ — ЦЕЛИКОМ, СЕРВЕРУ — СЛОВО. Подробность беды печатается в журнал
    # запуска рутины (`say`), а в отчёт уходит короткий код из `REPORT_CODES`:
    # свободная строка увезла бы на сервер местные пути и трассировки, а
    # обещано «JSON без текста» (инвариант 22).
    try:
        report = do_job(actor, one, job, env, args)
    except Stop as beda:
        report = {"outcome": beda.outcome, "error": beda.code}
        say(beda.message, env, stream=sys.stderr)
    except client.ClientError as beda:
        # Своя беда соседнего скрипта (нет ключа Zoom, не настроена Библиотека)
        # — это тоже «не вышло»: сервер обязан узнать причину, а не тишину.
        # Слово причины — имя самой беды клиента: `usage`, `refused`, `unreachable`.
        report = {"outcome": client.TRANSCRIPT_FAILED,
                  "error": type(beda).__name__.lower()}
        say(beda.message, env, stream=sys.stderr)
    except Exception as beda:                 # поломка самого скрипта — тоже отчёт
        report = {"outcome": client.TRANSCRIPT_FAILED, "error": CRASH}
        say(f"Поломка скрипта: {type(beda).__name__}: {beda}", env, stream=sys.stderr)
    return transcript_report(one, job, report, env, url, key)


def transcript_report(one: dict, job: dict, report: dict, env: dict,
                      url: str, key: str) -> int:
    """Отчёт о расшифровке со словами пакета о себе. Код — как у `run`."""
    report["job_id"] = job["id"]
    # СЛОВО О ГОТОВНОСТИ «МОИХ ВСТРЕЧ» — при ЛЮБОМ исходе (#475, Р13). По нему
    # сервер помнит последнее сказанное и решает, предлагать ли человеку это
    # место. Скажи его только при успехе — и у того, чей автомат неделю
    # спотыкается о Zoom, «Мои встречи» не появились бы в выборе никогда.
    #
    # ТЕКСТ ТОЛЬКО ЧТО ЛЁГ ТУДА — ДОКАЗАТЕЛЬСТВО СИЛЬНЕЕ ПРОВЕРКИ, и второй обход
    # сети ради того же ответа не нужен: отчёт и так ждёт своей очереди дольше,
    # чем стоило бы. В остальных случаях проверка живая — и она ограничена
    # таймаутом git (`library.GIT_TIMEOUT_SEC`), поэтому задержать отчёт
    # навсегда не может ни при какой сети.
    report[client.MY_MEETINGS_FIELD] = (report.get("repo") == library.PERSONAL_REPO
                                        or my_meetings_ready(env))
    # УМЕНИЕ «РАЗБОР» — тоже при любом исходе (#509, #514): облачная рутина
    # клонирует пакет заново каждый запуск, и первый же отчёт новой сборки
    # включает умение, даже если сама эта расшифровка споткнулась о Zoom.
    report[client.REVIEWS_FIELD] = True
    answer = client.transcripts(one["id"], report, url=url, key=key)
    if report["outcome"] == client.TRANSCRIPT_DONE:
        say(f"Готово: {report['repo']}/{report['path']}", env)
        say(f"Сервер принял отчёт: {answer.get('outcome')}, задание "
            f"{answer.get('status')}.", env)
        return client.EXIT_OK
    say(f"Сервер принял отчёт «{report['outcome']}»: {answer.get('outcome')}, задание "
        f"{answer.get('status')}. Человеку скажет сам сервер.", env)
    return client.EXIT_USAGE


# ---------------------------------------------------------------------------
# Подготовка разбора: папка, в которой модели остаётся извлечение (#514)
# ---------------------------------------------------------------------------
def prepare_review(one: dict, env: dict) -> Path:
    """Папка разбора со всем, что делается до извлечения, — или `NotPrepared`.

    КОМАНДЫ — ТЕ ЖЕ, ЧТО У СКИЛЛА НА КОМПЬЮТЕРЕ, и они зовутся, а не
    повторяются: карточку кладёт `meeting.py meetings --pick`, выгрузку делает
    `meeting.py tasks`, текст ищет `meeting.state` по карточке, папку называет
    `meeting.folder_for`. Разойдись две копии — окно разбора и компьютер
    разбирали бы одну встречу в разных папках и по разным текстам.

    ПОРЯДОК: карточка → Библиотека → текст → выгрузка. Карточка первой: по ней
    выбирается репозиторий (адрес текста из отчёта задания или место) и ищется
    текст. Текст — раньше выгрузки: без текста разбирать нечего, и слово причины
    у отчёта должно назвать именно это.

    БИБЛИОТЕКА ТЯНЕТСЯ ОДНИМ РЕПОЗИТОРИЕМ, если он известен: машина рутины пустая,
    и клонировать всю Библиотеку ради одного текста незачем (довод
    `ensure_clone`). Не известен — вся. Отказ `pull` подготовку не останавливает:
    судит результат — нашёлся ли текст.

    ВЫГРУЗКА — ПО ОТДЕЛУ ВСТРЕЧИ, номером: по нему соберётся пакет. У встречи без
    отдела — без него, и пакет уходит без отдела (#522): задачи и уведомления
    людям, итога в группу нет.
    """
    # Импорт здесь, а не в шапке: `meeting.py` сам берёт у автомата таблицы мест
    # и слов, и встречный импорт в шапке держался бы лишь до первой константы,
    # которую один из двух модулей захочет прочитать при загрузке.
    import meeting

    day = day_of(one).strftime(DATE_FMT)
    review = meeting.folder_for(Namespace(date=day, folder=None))
    code, _, _ = run_script(meeting, ["meetings", "--date", day,
                                      "--pick", str(one["id"])], env)
    if code != client.EXIT_OK:
        raise NotPrepared(f"Карточку встречи с сервера не взять (код {code}) — "
                          f"см. вывод выше.", REVIEW_EXPORT_FAILED)
    repo = meeting.place_repo(meeting.meeting_card(review), env)
    code, _, _ = run_script(library, ["pull"] + (["--repo", repo] if repo else []), env)
    if code != client.EXIT_OK:
        say(f"Библиотека не обновилась (код {code}) — текст встречи ищу в том, что есть.",
            env, stream=sys.stderr)
    if not meeting.state(review, env, day_of(one))["transcript"]:
        raise NotPrepared("Текста встречи в Библиотеке нет — разбирать нечего. Расшифровка "
                          "этой встречи в Библиотеку не ложилась или лежит под другим "
                          "названием.", REVIEW_NO_TRANSCRIPT)
    team = (one.get("team") or {}).get("id")
    code, _, _ = run_script(meeting, ["tasks", "--date", day]
                            + (["--team", str(team)] if team else []), env)
    if code != client.EXIT_OK:
        raise NotPrepared(f"Выгрузка задач с сервера не удалась (код {code}) — "
                          f"см. вывод выше.", REVIEW_EXPORT_FAILED)
    return review


def review_job(one: dict, job: dict, env: dict, url: str, key: str) -> int:
    """Подготовка разбора и её исход: строка-указание — или отчёт «разбор не вышел».

    Строка-указание печатается ПОСЛЕДНЕЙ и одна: по ней инструкция рутины
    переходит в режим разбора, и дата встречи для команд разбора названа строкой
    выше. Любая беда подготовки — своя, соседнего скрипта или поломка — отчёт
    со словом причины, а подробность — в журнал запуска (инвариант 22).
    """
    try:
        review = prepare_review(one, env)
    except NotPrepared as beda:
        code, message = beda.code, beda.message
    except client.ClientError as beda:
        code, message = CRASH, beda.message
    except Exception as beda:                 # поломка подготовки — тоже отчёт
        code, message = CRASH, f"Поломка подготовки разбора: {type(beda).__name__}: {beda}"
    else:
        # ЧЕЙ ЗАПУСК (#518, довод — у `SWEEP_MARK`): по этой записи превью скажет
        # серверу, вести ли письмо «разбор готов» в окно сигнала.
        (review / RUN_MARK).write_text(json.dumps(
            {"job_id": job["id"], "signalled": not sweep_mark().is_file()},
            ensure_ascii=False), encoding="utf-8", newline="\n")
        say(f"Разбор подготовлен: {review} — команды разбора зови с --date "
            f"{day_of(one).strftime(DATE_FMT)}.", env)
        say(f"{REVIEW_POINTER}: читай {REVIEW_RULES}", env)
        return client.EXIT_OK
    say(message, env, stream=sys.stderr)
    answer = client.review_failed(one["id"], {"job_id": job["id"], "error": code},
                                  url=url, key=key)
    client.check_meetings(answer)
    say(f"Сервер принял отчёт «разбор не вышел» ({code}): {answer.get('outcome')}, "
        f"разбор {answer.get('review_status')}. Человеку скажет сам сервер.", env)
    return client.EXIT_USAGE


# ---------------------------------------------------------------------------
# Команда `awaiting`: вечерний добор
# ---------------------------------------------------------------------------
def cmd_awaiting(args, env: dict) -> int:
    """Что ещё ждёт автомата — расшифровки и разборы. Работы не делает — только
    называет задания, каждое его составом работы.

    И оставляет метку вечернего прохода (`SWEEP_MARK`): список «что осталось»
    спрашивает только он, и разбор, подготовленный после этого на той же машине,
    — не окно сигнала.
    """
    key = client.access_key(env)
    url = client.base_url(env)
    mark = sweep_mark()
    mark.parent.mkdir(parents=True, exist_ok=True)
    mark.write_text(json.dumps({"at": datetime.now().isoformat(timespec="seconds")}),
                    encoding="utf-8", newline="\n")
    _, found = awaiting_jobs(url, key)
    rows = [{"job_id": job.get("id"), "meeting_id": one.get("id"),
             "title": one.get("title"), "date": one.get("date"),
             "start_time": one.get("start_time"), "place": job.get("place"),
             "team": job.get("team"),
             # Состав работы (#514): по нему инструкция рутины ставит расшифровки
             # вперёд, а задание с разбором — последним.
             "work": job.get("work") or TRANSCRIPT_WORK,
             "status": job.get("status"), "names_expected": job.get("names_expected")}
            for one, job in found]
    if getattr(args, "as_json", False):
        print(clean(json.dumps({"jobs": rows}, ensure_ascii=False, indent=2), env))
        return client.EXIT_OK
    if not rows:
        say("Автомата не ждёт ни одно задание — делать нечего.", env)
        return client.EXIT_OK
    # Незнакомый состав называется своим словом и в строке, и в сводке — иначе
    # сумма по составам разошлась бы с числом заданий.
    said = [WORK_WORDS.get(row["work"], row["work"]) for row in rows]
    say(f"Ждут автомата: {len(rows)} — "
        + ", ".join(f"{words}: {said.count(words)}" for words in dict.fromkeys(
            [*WORK_WORDS.values(), *said]) if words in said), env)
    for row, words in zip(rows, said):
        # Место, а не отдел: у задания без отдела оно бывает и «Мои встречи», и
        # написать про такое «совет» значило бы соврать человеку в журнале.
        where = f" · {row['team'] or PLACE_WORDS.get(row['place'], 'совет')}"
        say(f"  · задание {row['job_id']} · {words} — "
            f"«{row['title']}» {row['date']} {row['start_time'] or ''}{where} "
            f"({row['status']})", env)
    say("Каждое: python avtomat.py run --job <номер>", env)
    return client.EXIT_OK


# ---------------------------------------------------------------------------
# Команда `check`: готовы ли «Мои встречи» — и слово об этом серверу
# ---------------------------------------------------------------------------
def cmd_check(args, env: dict) -> int:
    """Самопроверка автомата: работу не делает, говорит серверу слова о себе.

    ЗАЧЕМ ОТДЕЛЬНАЯ КОМАНДА. Первый раз о готовности «Моих встреч» сервер узнаёт
    от пробного запуска мастера «подключи автомат» — а заданий в тот момент нет
    ни одного, и слово ехать не с чем. Проверяется то же самое, что уезжает
    полем отчёта, тем же кодом: два судьи одной готовности однажды разошлись бы,
    и человек получил бы «Мои встречи» в выборе там, где транскрипт не ляжет.

    Слово УХОДИТ В ОБОИХ СЛУЧАЯХ. «Не готов» — такая же новость, как «готов»: по
    ней сервер перестанет предлагать место, которого нет.

    УМЕНИЕ «РАЗБОР» ПЕЧАТАЕТСЯ ПО ОТВЕТУ СЕРВЕРА, а не по тому, что пакет его
    сказал (#516). Сервер старше слова отвергает его по имени, а клиент молча
    снимает слово и повторяет (`oblako_client._without_unknown_self_words`), и
    пробный запуск мастера хвалил бы умение, о котором сервер не узнал: разбор этому автомату не
    ставился бы, а никто бы не знал почему. Код возврата от умения не зависит —
    он о «Моих встречах», и мастер читает его, как прежде.
    """
    key = client.access_key(env)
    url = client.base_url(env)
    ready = my_meetings_ready(env)
    answer = client.my_meetings(ready, url=url, key=key)
    say("«Мои встречи» готовы: личная расшифровка ляжет в "
        f"{library.PERSONAL_REPO}." if ready else NO_PERSONAL_REPO, env)
    say(f"Сервер принял слово: готовность {answer.get('ready')}, "
        f"сказано {answer.get('said_at')}.", env)
    say(REVIEWS_TAKEN if answer.get("reviews") else REVIEWS_UNKNOWN, env)
    return client.EXIT_OK if ready else client.EXIT_USAGE


COMMANDS = {"run": cmd_run, "awaiting": cmd_awaiting, "check": cmd_check}


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Автомат Oblako: расшифровка записанной встречи в Библиотеку")
    subs = parser.add_subparsers(dest="command", required=True)

    run = subs.add_parser("run", help="весь путь одного задания и отчёт серверу")
    run.add_argument("--job", type=int, required=True, help="номер задания из сигнала")
    run.add_argument("--repo", help="репозиторий Библиотеки, если своего не выбрать")

    waiting = subs.add_parser("awaiting", help="что ещё ждёт автомата: расшифровки и разборы")
    waiting.add_argument("--json", action="store_true", dest="as_json",
                         help="машинный вид для агента")

    subs.add_parser("check", help="готовы ли «Мои встречи» — и слово об этом серверу")
    return parser


def main(argv=None) -> int:
    client.setup_console()
    args = _parser().parse_args(argv)
    env = settings()
    try:
        return COMMANDS[args.command](args, env)
    except client.ClientError as error:
        return client.fail(error, secrets(env))
    except Exception:                         # трассировка — только очищенная от ключей
        return client.crash(secrets(env))


if __name__ == "__main__":
    sys.exit(main())
