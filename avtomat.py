# Перечень СЕРВЕРА (`core.REVIEW_ERRORS`), и довод тот же, что у `REPORT_CODES`:
# в поле едет слово, а не строка беды. Карточка встречи — такая же выгрузка с
# сервера перед разбором, как и задачи, и слово у них одно: сервер другого не
# знает, а незнакомое положил бы безымянным `unknown`.
REVIEW_NO_TRANSCRIPT = "no_transcript"   # текста встречи в Библиотеке нет
REVIEW_EXPORT_FAILED = "export_failed"   # карточка или выгрузка задач не взялись
REVIEW_CODES = (REVIEW_NO_TRANSCRIPT, REVIEW_EXPORT_FAILED, CRASH)


class Stop(Exception):
    """Работа не вышла, и об этом надо ОТЧИТАТЬСЯ, а не промолчать.

    Исход несётся вместе с причиной: «записи ещё нет» сервер вернёт в очередь и
    попробует снова, «не вышло» — закроет задание и позовёт человека. Разница
    между ними стоит человеку либо лишнего часа ожидания, либо потерянной
    расшифровки, поэтому она названа в каждом месте, где работа обрывается.

    Причин у беды ДВЕ, и они для разных читателей: `message` — человеку в журнал
    запуска рутины, целиком и по-русски; `code` — серверу в поле `error`, одним
    коротким словом из `REPORT_CODES`. Текста встречи, местных путей и трассировок
    на сервер не уезжает (инвариант 22).
    """

    def __init__(self, outcome: str, message: str, code: str):
        super().__init__(message)
        self.outcome = outcome
        self.message = message
        self.code = code


class NotPrepared(Exception):
    """Разбор не подготовлен — отчитаться «разбор не вышел», а не промолчать.

    Исход у разбора один, поэтому поля два, а не три, как у `Stop`: `message` —
    человеку в журнал запуска, `code` — серверу словом из `REVIEW_CODES`.
    """

    def __init__(self, message: str, code: str):
        super().__init__(message)
        self.message = message
        self.code = code


