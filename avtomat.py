def repo_for(place, team, env: dict, named=None) -> "library.Repo":
    """Куда писать — по МЕСТУ задания, а не по признаку «есть ли отдел» (#480).

    Место называет сервер (`place` в задании, #476), и он же его судил: отдел
    организатора, готовность «Моих встреч» и слово человека сведены там в одно
    слово из трёх. Здесь остаётся МЕХАНИЧЕСКИЙ перевод слова в репозиторий:

        team      репозиторий отделов, файл внутри `Отделы/<Отдел>/`
        council   `sovet` — документы всей компании, от корня
        personal  `oblako-lichnoe` — «Мои встречи», тоже от корня

    КОРНЕВЫХ РЕПОЗИТОРИЯ ДВА, И РАЗЛИЧАЮТСЯ ОНИ ПО ИМЕНИ. Признак «корневой»
    верен про оба, и выбор по нему отказал бы у каждого, у кого настроены и
    совет, и «Мои встречи», — то есть у всех после раздачи 1.13.

    МЕСТА НЕТ — ЧИТАЕМ ПО-СТАРОМУ: отдел есть, значит отделы; нет — значит
    совет. Так выглядит задание сервера, который ещё не обновился, и ломать его
    нельзя ни в одну сторону: сервер и пакет выкатываются порознь. В «Мои
    встречи» такое задание не уедет никогда — его там не ждут.

    СЛОВО, КОТОРОГО МЫ НЕ ЗНАЕМ, — ОТКАЗ, а не «ну пусть будет совет»: чужой
    разговор, легший в совет, читается как настоящий, и молчаливая догадка здесь
    дороже отказа. Разовое отступление человека — `--repo`.
    """
    found = library.repos(env)
    if named:
        return library.pick(named, found)
    where = (place or "").strip().lower() or (TEAM_PLACE if team else COUNCIL_PLACE)
    if where == PERSONAL_PLACE:
        fit = [one for one in found if one.name.lower() == library.PERSONAL_REPO]
        said = None                       # у «Моих встреч» отказ свой, см. ниже
    elif where == TEAM_PLACE:
        fit = [one for one in found if not one.root_level]
        said = f"внутри Отделы/{team}"
    elif where == COUNCIL_PLACE:
        fit = [one for one in found if one.name.lower() == library.COUNCIL_REPO]
        said = "от корня (совет)"
    else:
        raise Stop(client.TRANSCRIPT_FAILED,
                   f"Сервер назвал место расшифровки, которого автомат не знает: "
                   f"{place!r}. Обнови пакет — или назови репозиторий сам: "
                   f"avtomat.py run --repo <имя>.", NO_REPO)
    if len(fit) == 1:
        return fit[0]
    raise Stop(client.TRANSCRIPT_FAILED,
               NO_PERSONAL_REPO if said is None else
               (f"Не выбрать репозиторий Библиотеки для записи {said}: подошло "
                f"{len(fit)} из {len(found)}. Назови его: avtomat.py run --repo <имя>."),
               NO_REPO)


def my_meetings_ready(env: dict) -> bool:
    """Настроены ли «Мои встречи» у ХОЗЯИНА ключа — и правда ли они работают.

    Слово это уезжает на сервер при каждом отчёте (#475): по нему он решает,
    предлагать ли человеку «Мои встречи» местом расшифровки. Соврать в обе
    стороны одинаково дорого — поэтому проверяется не запись в `.env`, а
    достижимый клон: адрес есть, а прав на репозиторий нет — транскрипт не ляжет
    туда никогда, и обещать это место человеку нельзя.

    ПРОВЕРКА ЖИВАЯ, И ОТКАЗ СЕТИ — ЭТО «НЕ ГОТОВ», А НЕ ПОЛОМКА ОТЧЁТА. Сам
    отчёт важнее слова о готовности: задание, о котором не отчитались, висит у
    сервера в полёте, а «не готов» лишь вернёт человеку вопрос о месте.
    """
    try:
        found = library.repos(env)
    except client.ClientError:
        return False                      # Библиотека не настроена вовсе
    fit = [one for one in found if one.name.lower() == library.PERSONAL_REPO]
    if not fit:
        return False
    try:
        code, _, _ = run_script(library, ["pull", "--repo", fit[0].name], env)
    except Exception:                     # поломка проверки не ломает отчёт
        return False
    return code == client.EXIT_OK


def ensure_clone(repo: "library.Repo", env: dict) -> None:
    """Завести клон целевого репозитория, если его на этой машине нет.

    В ОБЛАКЕ КЛОНОВ НЕТ НИКОГДА. Машина рутины создаётся под каждый сигнал
    заново и пустой: `.env` в ней нет, папок нет, Библиотеки нет. На компьютере
    человека клоны завёл мастер установки, поэтому дыра не видна там вовсе — а в
    облаке она закрывала автомату дорогу целиком: `put` отказывал «клона нет —
    записывать некуда», и ни одна планёрка не доезжала до Библиотеки (#465).

    Заводится РОВНО ТОТ репозиторий, куда ляжет файл (его выбрал `repo_for` по
    отделу задания). Тянуть всю Библиотеку ради одного транскрипта незачем:
    репозиториев несколько и станет больше, а доступ у личного ключа есть не ко
    всем — лишний клон стоил бы минут облака за каждую планёрку и однажды
    свалился бы на чужом.

    Отказ сети здесь — такой же отказ Библиотеки, как и все прочие: он
    отчитывается тем же словом (`LIBRARY_PUT`), и человека зовёт сервер. Молчать
    о нём нельзя — молчание стоит человеку расшифровки.
    """
    if repo.cloned:
        return
    code, _, _ = run_script(library, ["pull", "--repo", repo.name], env)
    if code != client.EXIT_OK:
        raise Stop(client.TRANSCRIPT_FAILED,
                   f"Клона Библиотеки не было, и завести его не вышло (код {code}) — "
                   f"см. вывод выше.", LIBRARY_PUT)


def to_library(text: Path, one: dict, job: dict, sign: str, env: dict,
               named=None) -> dict:
    """Записать транскрипт в Библиотеку и отправить его. Путь считает `library.py`.

    МЕСТО НАЗЫВАЕТ ЗАДАНИЕ, а не отдел серии: его мог выбрать сам человек кнопкой
    в Telegram, и это его решение старше умолчания. Отдел при месте `team` —
    оттуда же: у серии он один, а у задания бывает свой.

    Отправка обязательна и входит в успех. Коммит без `push` живёт в машине
    рутины, которую облако выключит через минуту, — а отчёт «готово» сказал бы
    человеку, что текст в Библиотеке, и он пошёл бы читать пустое место.
    """
    team = job.get("team")
    repo = repo_for(job.get("place"), team, env, named)
    ensure_clone(repo, env)
    when = day_of(one)
    where = Namespace(team=team, title=title_of(one))
    target, _ = library.place(repo, "transcript", when, where)

    argv = ["put", "--repo", repo.name, "--kind", "transcript",
            "--date", when.strftime(DATE_FMT), "--title", where.title,
            "--file", str(text), "--as-automaton", sign]
    if team and not repo.root_level:
        argv += ["--team", str(team)]
    code, _, _ = run_script(library, argv, env)
    if code != client.EXIT_OK:
        raise Stop(client.TRANSCRIPT_FAILED,
                   f"Библиотека не приняла транскрипт (код {code}) — см. вывод выше.",
                   LIBRARY_PUT)
    code, _, _ = run_script(library, ["push", "--repo", repo.name], env)
    if code != client.EXIT_OK:
        raise Stop(client.TRANSCRIPT_FAILED,
                   f"Транскрипт записан, но не отправлен в Библиотеку (код {code}): "
                   f"в облаке эта копия не переживёт запуск.", LIBRARY_PUSH)
    return {"repo": repo.name, "path": target, "sha256": client.digest(text)}


