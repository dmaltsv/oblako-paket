NO_DATE = "без даты"


def _dates_of(item: dict) -> str:
    """Даты пункта словами. У новой задачи и у правки они значат РАЗНОЕ.

    В `add` пустая дата — просто её отсутствие. В `edit` у обеих дат три
    состояния, и `null` там — «снять»; показать его как «нет даты» значило бы
    спрятать от человека снятие срока, которое он подтверждает словом «отправляй».

    НОВАЯ ЗАДАЧА БЕЗ ОБЕИХ ДАТ НАЗЫВАЕТСЯ ВСЛУХ (#473, #480). Такая задача
    законна: на планёрке «займись складом» звучит чаще, чем дата, и срок за
    человека не выдумывают — он ляжет получателю в «Не запланировано». Но пустое место в
    строке превью читается как «дата есть, просто не показали», и руководитель
    узнал бы правду уже после слова «отправляй». Поэтому — слово, а не пустота.
    У правки такого слова нет: там пустой хвост означает «даты не трогаем».

    Просьба о комментарии у новой задачи — хвостом этой строки (`WITH_COMMENT`):
    «рабочий день 2026-08-10 · с комментарием», без дат — «без даты · с комментарием».
    """
    parts = []
    for key, label in (("due", "рабочий день"), ("deadline", "дедлайн")):
        if item.get(key):
            parts.append(f"{label} {item[key]}")
    for key, label in (("new_due", "рабочий день →"), ("new_deadline", "дедлайн →")):
        if key in item:
            parts.append(f"{label} {item[key] or 'снять'}")
    if "new_text" in item:
        parts.append(f"текст → «{item['new_text']}»")
    if item.get("op") == "add":
        if not parts:
            parts.append(NO_DATE)
        if item.get("needs_comment"):
            parts.append(WITH_COMMENT)
    return " · ".join(parts)


def _head_of(item: dict) -> str:
    """Главная строка пункта в превью и в уточнениях: задача правки — номером и
    текстом, новая — названием, важная — с 🔥 перед ним (`IMPORTANT_MARK`)."""
    if str(item.get("op", "?")) in ("close", "edit"):
        return f"[#{item.get('task_id')}] {item.get('task_text', '')}"
    mark = IMPORTANT_MARK if item.get("importance") == IMPORTANT else ""
    return f"{mark}{item.get('text', '')}"


def preview_lines(package: dict, snapshot: dict, marks: list | None = None,
                  notes: list | None = None) -> tuple:
    """Превью по людям и список расхождений со снимком.

    ``marks`` — пометки устаревших пунктов словами сервера, ``notes`` — пометки
    «уйдёт иначе, чем записан», по одной на пункт пакета (`stale_marks`,
    `server_notes`): печатаются в строке пункта (✂️ и ℹ️), со снимком не спорят.
    Расхождения у пакета черновика на сервере зовущий не судит (`show_review`).

    Сверяется то, на что есть местный ответ: тот ли человек, из своего ли он
    отдела и та ли задача. Чему местного ответа нет — здесь не судится (шапка
    файла, «Судья пакета — сервер»).

    КРУГА ДВА, И ОНИ РАЗНЫЕ (#467): новую задачу разбор ставит любому активному
    сотруднику компании (справочник получателей), а закрывает и правит только у
    состава своего отдела (снимок с задачами). Сверка повторяет здесь ровно эту
    развилку — и повторяет намеренно, теми же словами, что скажет сервер: узнать
    об отказе на превью можно до слова «отправляй», а на отправке — уже после того,
    как руководитель поверил, что разбор сдан.

    ТЁЗКИ РАЗЛИЧАЮТСЯ НОМЕРОМ (#467, решение 4). Разбор опознаёт людей по имени,
    сказанному вслух, и двух Ольг в компании отличить на слух нечем: отдел
    спасает не всегда — тёзки бывают и в одном. Имя, которое носят двое, здесь
    печатается с `id`, потому что превью — единственное место, где руководитель
    видит выбор ДО слова «отправляй». Заодно это чинит и группировку: блоки
    складываются по показанному имени, и голые тёзки слились бы в один блок,
    показав задачи двух людей как задачи одного.
    """
    people = _people_index(snapshot)
    listed = _recipients_index(snapshot)
    # Снимок, снятый до #467, справочника не несёт вовсе. Молчаливое «человека
    # нет» увело бы руководителя чинить черновик вместо того, чтобы обновить
    # снимок, — поэтому причина называется своей фразой.
    stale = "recipients" not in snapshot
    # Тёзки — по ОБОИМ кругам разом и по людям, а не по строкам: состав отдела
    # лежит и в справочнике, и совпадение человека с самим собой тёзкой не
    # делает. Считается один раз на весь пакет: имя неоднозначно в компании, а
    # не в пункте.
    known = {**listed, **people}
    namesakes = {name for name, count in Counter(
        person.get("name") for person in known.values()).items() if name and count > 1}
    by_person: dict = {}
    problems: list = []
    items = package.get("items") or []
    marked = marks if isinstance(marks, list) and len(marks) == len(items) else [None] * len(items)
    noted = notes if isinstance(notes, list) and len(notes) == len(items) else [None] * len(items)
    for number, (item, mark, note) in enumerate(zip(items, marked, noted), start=1):
        op = str(item.get("op", "?"))
        person_id = item.get("person_id")
        person = people.get(person_id)
        outsider = person is None
        if outsider:
            person = listed.get(person_id)
        if person is None:
            problems.append(
                f"пункт {number}: человека id={person_id} нет в снимке"
                + (" — снимок снят без справочника получателей (старый сервер "
                   "или старая выгрузка): сделай выгрузку заново"
                   if stale else
                   " и нет в справочнике компании — пакет будет отвергнут целиком"))
        elif outsider and op != "add":
            problems.append(f"пункт {number}: «{person.get('name')}» не из отдела разбора — "
                            f"закрыть или изменить его задачу можно только на его планёрке")
        # Сравнение с None, а не на истинность: сервер судит `due` тем же
        # `is not None`, и пустая строка обязана отвергнуться ЗДЕСЬ, а не после
        # слова «отправляй».
        elif outsider and item.get("due") is not None:
            problems.append(f"пункт {number}: «{person.get('name')}» не из отдела разбора — "
                            f"поставить ему можно дедлайн (deadline), а рабочим днём "
                            f"(due) распоряжается он сам")
        elif not outsider and op in ("close", "edit"):
            task = _task_index(person).get(item.get("task_id"))
            if task is None:
                problems.append(f"пункт {number}: у «{person.get('name')}» нет открытой "
                                f"задачи id={item.get('task_id')}")
            elif (task.get("text") or "").strip() != (item.get("task_text") or "").strip():
                problems.append(f"пункт {number}: текст задачи id={item.get('task_id')} "
                                f"разошёлся со снимком — в снимке «{task.get('text')}»")
        name = (_person_label(person, outsider, person.get("name") in namesakes)
                if person is not None else f"id={person_id}")
        by_person.setdefault(name, {}).setdefault(op, []).append((item, mark, note))

    lines = []
    for name in sorted(by_person):
        lines.append(f"### {name}")
        for op in ("close", "add", "edit"):
            listed_items = by_person[name].get(op)
            if not listed_items:
                continue
            lines.append(f"{OP_TITLE.get(op, op)}:")
            for item, mark, note in listed_items:
                tail = _dates_of(item)
                lines.append(f"  {OP_MARK.get(op, '•')} {_head_of(item)}"
                             + (f" — {tail}" if tail else "")
                             + (f" — ✂️ {mark}" if mark else "")
                             + (f" — ℹ️ {note}" if note else ""))
        lines.append("")
    return lines, problems


def clarify_lines(asked: list) -> list:
    """Уточнения черновика — отдельным блоком (Р4): вопрос и предложенное действие.

    В пакет они не идут и со снимком не сверяются: у предложенной задачи человека
    бывает не названо вовсе — это и есть вопрос. Вид показа человеку задаёт скилл
    разбора (шаг 5); здесь — чтобы превью не молчало о том, что не уйдёт.
    """
    lines = ["⚠️ Требует уточнения — не уйдёт, пока человек не ответит:"]
    for item in asked:
        op = str(item.get("op", "?"))
        who = item.get("person_name") or (f"id={item['person_id']}" if item.get("person_id")
                                          else "исполнитель не назван")
        lines.append(f"  ❓ {item.get(CLARIFY)} — предложено: {OP_MARK.get(op, '•')} "
                     f"{who}: {_head_of(item)}")
    return lines


def show_review(review: Path, package: dict, snapshot: dict, source: str, *,
                judged_by_server: bool = False, server: dict | None = None) -> int:
    """Разбор по людям, уточнения и сверка со снимком — печатью. Код 1 — расхождения.

    Один показ на превью и на отказы «черновик поправили» (`confirm`, `send_draft`):
    свежий вид человек видит тем же видом, что всегда. Уточнения в сверку не
    входят — их пунктов в пакете не будет.

    ЧЕРНОВИК НА СЕРВЕРЕ СВОИМ СНИМКОМ НЕ СУДИТСЯ (``judged_by_server``, ревью SP-1):
    его пункты судит сервер, как у экрана разбора, — и говорит о них сам, словами
    одной с отправкой сборки (``server`` — его черновик, круг 2 ревью, A-1):
    устаревшее отрежет (✂️, `stale_marks`), пункт, который уйдёт иначе, чем записан,
    помечен (ℹ️, `server_notes`). Местная сверка остановила бы разбор, который
    экран отправил бы; поэтому здесь снимок — только имена людей. Пометки — по
    пункту на пункт черновика, уточнения в счёте. Код тогда всегда 0.
    """
    items = package.get("items") if isinstance(package.get("items"), list) else []
    blank = [None] * len(items)
    every = stale_marks(server) if judged_by_server else blank
    notes = server_notes(server) if judged_by_server else blank
    tasks = [item for item in items if not clarification(item)]
    task_marks = [mark for item, mark in zip(items, every) if not clarification(item)]
    task_notes = [note for item, note in zip(items, notes) if not clarification(item)]
    asked = [item for item in items if clarification(item)]
    meeting = package.get("meeting") or {}
    lines, problems = preview_lines({**package, "items": tasks}, snapshot, task_marks,
                                    task_notes)
    if judged_by_server:
        problems = []
    print(f"Разбор: {meeting.get('kind', 'встреча')} {meeting.get('date', '')} · "
          f"пунктов {len(tasks)}" + (f" · уточнений {len(asked)}" if asked else "")
          + f" · источник {source}")
    # Сравнивается ПАКЕТ, а не байты: `confirm` срезает уточнения и ставит номер
    # встречи (`package_of`), и черновик от этого с подтверждённым не расходится.
    if source == DRAFT and (review / PACKAGE).is_file() and \
            package_of(review, package) != read_json(review / PACKAGE):
        print("Черновик расходится с подтверждённым пакетом — на него нужно новое «отправляй».")
    print("\n".join(lines))
    if asked:
        print("\n".join(clarify_lines(asked)))
    empty = no_tasks_words(review, package) if source == DRAFT else None
    if problems:
        print("Расхождения со снимком — пакет в таком виде сервер отвергнет:")
        for line in problems:
            print(f"  · {line}")
    elif empty:
        print(empty)
    elif judged_by_server:
        cut = sum(1 for mark in task_marks if mark)
        noted = sum(1 for note in task_notes if note)
        told = ([f"Устаревших пунктов {cut} (пометка ✂️ — слова сервера): при отправке "
                 f"сервер их отрежет, остальное уйдёт."] if cut else []) + \
               ([f"Пунктов, которые уйдут иначе, чем записаны, {noted} (пометка ℹ️ — слова "
                 f"сервера)."] if noted else [])
        print(" ".join(told) + " Покажи их человеку как есть." if told else
              "Пункты судит сервер при отправке: устаревшие отрежет с пометкой, остальное "
              "уйдёт.")
    else:
        print("Люди и задачи сошлись со снимком. Формат и права судит сервер при отправке.")
    return client.EXIT_USAGE if problems else client.EXIT_OK


def cmd_preview(args, env: dict) -> int:
    """Превью показывает ЧЕРНОВИК, пока он есть, — иначе подтверждённый пакет.

    Порядок именно такой: после правок руководителя агент переписывает черновик,
    и превью обязано показать новое. Показав вместо него уже подтверждённый
    пакет, оно рассказывало бы человеку о том, что он правил минуту назад.

    ЧЕРНОВИК НА СЕРВЕРЕ ПРЕВЬЮ СНАЧАЛА СВЕРЯЕТ (#514, #580) — тем же шагом, а не
    отдельной командой: превью модель зовёт после каждой правки и перед ответом
    человеку, а шаг, который нельзя забыть, надёжнее шага, который надо помнить.
    Сверяется черновик, который та же запись, что на сервере (`shared_draft`): в
    окне разбора и на компьютере автора. Показывается то, что вышло из сверки:
    правки экрана видны, своя правка, которую не пустил замок версии, заменена
    свежим черновиком (`sync_draft`). Ручной разбор на компьютере ничего не кладёт
    — его ведёт сам человек. Не сверяется — после отправки: применение черновик
    уже погасило.

    ПУНКТЫ ЧЕРНОВИКА НА СЕРВЕРЕ СУДИТ СЕРВЕР (ревью SP-1, круг 2 — A-1): своим
    снимком превью их не судит — снимок здесь только для имён, и свежей выгрузки
    ради него не делается, — а печатает слова сервера из той же сборки, что
    отправка (`show_review`): устаревшее он отрежет (✂️), пункт уйдёт иначе, чем
    записан (ℹ️). Пакет из файла (разбор без черновика на сервере) сверяется со
    СВЕЖИМ СНИМКОМ, как раньше (`fresh_snapshot`, #518): на компьютере — со снятым
    сегодня, в окне — с выгрузкой, сделанной этим же превью.

    КОДЫ ВЫХОДА — скилл ходит по ним (гейт «отправляй», ревью SP-2, SP-5):

    * 0 — показано; у черновика на сервере — версия, которую сервер и отправит;
    * 1 — у пакета из файла: расхождения со снимком (чинит черновик); у черновика
      на сервере: сервер не принял пункт при записи (`ITEM_REFUSED`) — исправить
      названное сервером и показать превью снова; у обоих — не с чем работать или
      «отстал сервер»: причина названа в выводе;
    * 2 / 3 — черновик с сервером не сверен (отказ / нет связи): без него человек
      не узнает о разборе, а правки экрана не дойдут до окна — ошибка, не
      предупреждение. Черновика на сервере больше нет (`DraftGone`) — тоже 2, со
      словами сервера: отправлять нечего. У пакета из файла свежей выгрузки не
      взять — код выгрузки;
    * 7 (`EXIT_DRAFT_CHANGED`) — подтянута правка экрана: выше свежий вид,
      «отправляй», сказанное до неё, к нему не относится;
    * 8 (`EXIT_REAPPLY`) — своя правка не легла поверх правки экрана: копия
      заменена свежей, правку человека наложить заново и показать превью снова.

    КРИВОЙ ПУНКТ СЕРВЕР НЕ КЛАДЁТ (круг 2 ревью, A-5): запись новой формы судит
    пункты по ключам и отказывает 400 с полем — на сервере остаётся прежний
    черновик, а превью разбора не показывает и кончается кодом 1 и словами
    `ITEM_REFUSED`: пункт, названный сервером (его слова и имя ключа из поля
    `field` отказа), исправить и показать превью снова. Письмо «разбор готов»
    уходит с первым ЛЁГШИМ черновиком.

    ССЫЛКУ НА ОКНО В ПИСЬМЕ «РАЗБОР ГОТОВ» СЕРВЕР ДАЁТ ТОЛЬКО ОКНУ СИГНАЛА
    (`signalled_window`): у вечернего прохода её нет, и слова превью говорят
    модели ровно то, что придёт человеку, — иначе она пообещала бы ссылку.
    """
    review = folder_for(args)
    source = review / (DRAFT if (review / DRAFT).is_file() else PACKAGE)
    package = read_json(source)
    if package is None:
        raise client.Usage(f"Разбора нет: положи его в {review / DRAFT} и покажи превью снова")
    drafted = source.name == DRAFT and shared_draft(review) and not sent_package(review)
    if drafted:
        snapshot = read_json(review / TASKS)
    else:
        snapshot, code = fresh_snapshot(review)
        if code != client.EXIT_OK:
            print("Свежую выгрузку задач не взять — сверки нет, показывать разбор нельзя. "
                  "Покажи превью ещё раз.", file=sys.stderr)
            return code
    if snapshot is None:
        raise client.Usage(f"Нет снимка задач ({review / TASKS}) — показывать разбор по людям "
                           f"не по чему. Сделай выгрузку: meeting.py tasks")
    said, failure, synced, live = None, None, client.EXIT_OK, None
    key = env.get(client.KEY_ENV)
    if drafted:
        try:
            package, said, synced, live = sync_draft(review, env, package)
        except client.ClientError as beda:
            failure = beda
    if isinstance(failure, client.Refused) and failure.status == 400:
        # Разбор не показывается: показанный, он читался бы положенным. Слова
        # сервера — человеческие, имя ключа он кладёт отдельно (`field`): модели
        # нужно и то, и другое — что сказать человеку и что чинить.
        print(ITEM_REFUSED)
        client.fail(failure, key)
        if failure.field:
            print(f"  · ключ пункта, на который отказал сервер: {failure.field}",
                  file=sys.stderr)
        return client.EXIT_USAGE
    found = show_review(review, package, snapshot, source.name, judged_by_server=drafted,
                        server=live)
    if said:
        print(said)
    if failure is not None:
        if isinstance(failure, DraftGone):
            return client.fail(failure, key)
        print("Черновик разбора с сервером не сверен — пока он не лёг, человек не узнает о "
              "разборе, а правки с экрана сюда не дойдут. Покажи превью ещё раз; не "
              "выходит — скажи это в показе.", file=sys.stderr)
        return client.fail(failure, key)
    return synced if drafted else found


def cmd_confirm(args, env: dict) -> int:
    # Страж слова — ПЕРВЫМ, до слова аргументом: в облаке слово аргументом
    # передаёт модель, и сказал ли его человек, знает только журнал окна.
    strazh.require_word_in_cloud()
    review = folder_for(args)
    draft, package = review / DRAFT, review / PACKAGE
    client.confirmed_by(args.word)
    if not draft.is_file():
        if confirmed_package(review):
            print(f"[Пропуск] пакет уже подтверждён: {package}")
            return client.EXIT_OK
        raise client.Usage(f"Черновика разбора нет: {draft}")
    body = read_json(draft)
    if body is None:                                   # битый JSON — до записи пакета
        raise client.Usage(f"Черновик не разобрать: {draft}")
    # Версия формата сверяется ЗДЕСЬ, а не только на сервере. Число живёт в трёх
    # местах — две константы (сервер и клиент, их равенство заперто тестом) и
    # ТЕКСТ инструкции агенту, по которому черновик и пишется. Разойдись текст с
    # константой — свежий пакет получал бы от сервера «сначала обновите пакет»
    # сразу после обновления, и человек ходил бы по кругу. Здесь круг рвётся:
    # отказ приходит до отправки и называет настоящую причину.
    version = body.get("version")
    if version != client.PACKAGE_FORMAT_VERSION:
        raise client.Usage(
            f"Черновик собран по версии формата {version!r}, а этот пакет говорит "
            f"на v{client.PACKAGE_FORMAT_VERSION}",
            ["исправь `version` в черновике разбора и подтверди заново",
             "если черновик писался по инструкции — устарела она, а не разбор: "
             "скажи владельцу системы"])
    empty = no_tasks_words(review, body)
    if empty:
        raise client.Usage(empty)
    # ВЕРСИЯ ПОСЛЕДНЕГО ПОКАЗА (#580, Р2) — у черновика, который та же запись, что
    # на сервере (`shared_draft`). «Отправляй» относится к показанному, и `send`
    # отправит ровно эту версию. Показанным черновик считается, только если своя
    # копия та же, что при последней сверке: правленый после превью или не
    # легший на сервер черновик человек не видел, а отправилась бы версия без его
    # правки.
    #
    # И ТОЛЬКО ЕСЛИ ОНА ВСЁ ЕЩЁ ЖИВАЯ (ревью SP-2): `confirm` зовут сразу за словом,
    # без превью, и показанная версия — та, что человек видел ДО слова. Экран мог
    # поправить черновик после показа: тогда живая версия другая, и слово к ней не
    # относится — ничего не подтверждено, свежий вид напечатан, код
    # `EXIT_DRAFT_CHANGED`. Держит это сверка с сервером, а не фраза инструкции.
    shown = None
    if shared_draft(review):
        copy = server_copy(review)
        if copy is None or copy["items"] != body.get("items"):
            raise client.Usage(NOT_SYNCED, [
                "сначала превью (meeting.py preview): оно сверится с сервером и положит правку",
                "превью кончилось кодом 7 или 8 — покажи человеку свежий вид и жди нового "
                "«отправляй»",
                'кодом 0 — снова confirm --word "<его слова>"'])
        answer = client.review_draft((meeting_card(review) or {}).get("id"),
                                     url=client.base_url(env), key=client.access_key(env))
        client.check_review_draft(answer)
        live = answer.get("draft")
        if not isinstance(live, dict) or live.get("job_id") != copy.get("job_id"):
            raise DraftGone(DRAFT_GONE)
        if live.get("version") != copy.get("version"):
            return show_changed(review, body, live, CONFIRM_CHANGED,
                                read_json(review / TASKS))
        shown = copy.get("version")
    # Пакет — черновик без уточнений и ключей черновика, с номером встречи
    # (`package_of`). Срезать и ставить нечего — пакет байт в байт черновик.
    confirmed = package_of(review, body)
    if confirmed != body:
        package.write_text(json.dumps(confirmed, ensure_ascii=False, indent=2),
                           encoding="utf-8")
    else:
        package.write_bytes(draft.read_bytes())
    # Отпечаток и слово пишутся ПОСЛЕ пакета: оборвись запись посередине, лучше
    # остаться с неподтверждённым пакетом, чем с подтверждением на пустое место.
    #
    # Отдел приезжает из СНИМКА, а не из флага: флага у `confirm` нет и быть не
    # должно — человек подтверждает тот разбор, который ему показали, а показан
    # он по составу снимка. Записанный здесь отдел потом сверяет отправка.
    #
    # Снимка в папке нет — ключ не пишется вовсе (#522): отдел неизвестен, а не
    # «без отдела». `team: null` значит разбор без отдела, и выводить его из
    # отсутствия выгрузки нельзя — называет его только снимок без отдела.
    snapped = read_json(review / TASKS) is not None
    (review / CONFIRMED).write_text(json.dumps({
        "package": digest(package),
        **({"team": snapshot_team(review)} if snapped else {}),
        "word": args.word.strip(),
        "at": datetime.now().isoformat(timespec="seconds"),
        **({DRAFT_VERSION: shown} if shown is not None else {}),
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f'Слово сказано («{args.word.strip()}») — разбор подтверждён: {package}')
    if shown is not None:
        print(f"Уйдёт версия черновика {shown} — та, что показана последней.")
    # Снимок без отдела — разбор без отдела (#522): флаг отдела при отправке тогда
    # не называется, иначе сверка отдела откажет.
    if snapped and snapshot_team(review) is None:
        print("Дальше: meeting.py send — без --team: разбор снят без отдела, "
              "итога в группу не будет")
    else:
        print("Дальше: meeting.py send --team <отдел>")
    return client.EXIT_OK


def _same_receipt_team(recorded, selector: str | None) -> bool:
    """Тот ли отдел назван, что записан в расписке.

    В расписке лежит СЕЛЕКТОР словом человека («1» или «Продажи»), а не номер:
    что назвали, то и записали. Поэтому два написания одного отдела расписка
    различить не может, и расхождение ведёт не к отказу, а к повторному вызову
    сервера — тот узнаёт пакет по отпечатку и второй раз задачи не заводит.

    ``selector=None`` — отправка без отдела (#522): совпадает только расписка без
    отдела (`team: null`).
    """
    if selector is None:
        return recorded is None
    return isinstance(recorded, str) and recorded.strip().lower() == selector.strip().lower()


def server_draft_job(review: Path) -> int | None:
    """Номер задания, если пакет собирается из ЧЕРНОВИКА С СЕРВЕРА, — иначе None.

    Черновик с сервера — в окне разбора и тот, что компьютер взял с сервера
    (`server_copy`, `from_server`), у встречи, чей разбор поставлен заданию из
    карточки (`review_ordered`). Ручной разбор на компьютере серверного черновика
    не имеет, и номера задания его пакет не несёт.

    ЖИВ ЛИ ЧЕРНОВИК, СУДИТ СЕРВЕР, А НЕ ЭТОТ СКРИПТ (ревью #518, этап 2): номер
    уезжает в пакете (`package_of`), и применение отвергает пакет закрытого
    разбора у любой двери — `meeting.py send`, `send_package.py --package`, CLI
    сервера. Прежняя проверка стояла здесь, у одной двери, и вторая принимала
    тот же пакет. Повтор уже применённого пакета сервер узнаёт по отпечатку
    раньше этого суда, и потерянный ответ досдаётся, а не отвергается.
    """
    copy = server_copy(review) or {}
    if not review_ordered(meeting_card(review)):
        return None
    if not (strazh.in_cloud() or copy.get("from_server")):
        return None
    return draft_job(review)


def write_receipt(review: Path, package: Path, team: str | None, code: int,
                  meeting: dict | None = None) -> None:
    """След отправки. Пишется ВСЕГДА — и на успех, и на отказ.

    ``team=None`` — разбор без отдела (#522): в расписке `team: null`.

    ``meeting`` — встреча, как её назвал отчёт сервера, у пакета, который сервер
    собрал сам из черновика (`send_draft`): день и вид там серверные, а не блока
    `meeting` своего файла, и досдача итога (`cmd_publish`) называет серверу их.
    """
    (review / RECEIPT).write_text(json.dumps({
        "package": digest(package),
        "team": team,
        "at": datetime.now().isoformat(timespec="seconds"),
        "exit_code": code,
        **({"meeting": meeting} if isinstance(meeting, dict) else {}),
    }, ensure_ascii=False, indent=2), encoding="utf-8")


def cmd_send(args, env: dict) -> int:
    """Отправка пакета. Повтор по тому же пакету на сервер не идёт.

    Сервер и сам узнал бы повтор по отпечатку, но идти к нему незачем: расписка
    уже знает исход, а лишний вызов на неполном итоге читался бы как «досдал».
    """
    # Страж слова в облаке — раньше отдела и отпечатка: подтверждённый пакет
    # на диске не значит, что человек сказал «отправляй» перед ЭТОЙ отправкой.
    strazh.require_word_in_cloud()
    review = folder_for(args)
    # Отдел или «без отдела» судится ДО всего остального: забытый флаг не должен
    # оставлять ни расписки, ни половины работы. «Без отдела» (#522) называет
    # снимок, по которому подтверждали разбор, — флага у `send` для него нет:
    # пустой `--team` значит «без отдела» только у подтверждённого без отдела,
    # и судит это `require_confirmation` ниже, до сети.
    team = (args.team or "").strip() or None
    package = review / PACKAGE
    if not (review / CONFIRMED).is_file() and (review / DRAFT).is_file():
        raise client.Usage(
            f"Этот пакет человек не подтверждал: {package}",
            ["сначала превью и слово человека: meeting.py preview, затем "
             'confirm --word "<его слова>"',
             f"черновик разбора на месте: {review / DRAFT}"])
    # Гейт «отправляй», сверку отдела и развилку «с отделом или без» судит ОДНА
    # функция на обоих клиентов — прямой `send_package.py` спрашивает её же.
    record = client.require_confirmation(package, team)
    st = state(review, env, meeting_date(getattr(args, "date", None)))
    # Пропуск повтора — только если отдел ТОТ ЖЕ. Расписка знает свой отдел, и
    # без сверки первая же опечатка в `--team` пряталась бы за «уже отправлено»:
    # разбор ушёл в чужой отдел, нужный не получил ничего, а человеку сказали,
    # что всё сделано.
    receipt_team = (st["receipt"] or {}).get("team")
    if st["sent"] and not args.dry_run and _same_receipt_team(receipt_team, team):
        code = (st["receipt"] or {}).get("exit_code", client.EXIT_OK)
        print(f"[Пропуск] этот пакет уже отправлен {(st['receipt'] or {}).get('at')} "
              f"(код {code}) — второй раз задачи не заводим.")
        if code == client.EXIT_PUBLISH_INCOMPLETE:
            print(f"Итог в группе неполон — досдать: meeting.py publish --team {team}")
        if code == client.EXIT_NO_PUBLISH:
            print("Итог в группу не публиковали — доделывать нечего.")
        return code

    # Черновик на сервере — та же запись, что у экрана (#580): уходит версия
    # последнего показа дверью черновика. Своим снимком она не судится (ревью
    # SP-1): устаревшее отрежет сервер с пометкой, как у экрана, — снимок нужен
    # только показу свежего вида, если черновик поправили после слова.
    shown = record.get(DRAFT_VERSION)
    if shown is not None:
        return send_draft(review, env, args, team, shown, read_json(review / TASKS))

    # Пакет из файла — та же сверка, что на превью, вторым разом перед самой
    # отправкой (#467). Превью показывают руководителю, а отправку зовут потом, и
    # между ними черновик успевают переписать: пункт чужому с рабочим днём,
    # закрытие чужой задачи или человек, которого в компании нет, уехали бы на
    # сервер и вернулись отказом всего пакета. Причины называются здесь теми же
    # словами, что скажет сервер. Снимка нет — сверять нечем, и это не повод не
    # отправлять: судит всё равно сервер. Устаревший снимок делается заново
    # (`fresh_snapshot`).
    snapshot, fetched = fresh_snapshot(review)
    if fetched != client.EXIT_OK:
        print("Свежую выгрузку задач не взять — без сверки не отправляю.", file=sys.stderr)
        return fetched
    if snapshot is not None:
        _, problems = preview_lines(read_json(package) or {}, snapshot)
        if problems:
            raise client.Usage(
                "Пакет разошёлся со снимком — сервер отвергнет его целиком:\n  · "
                + "\n  · ".join(problems),
                ["поправь черновик, покажи превью и подтверди заново",
                 "устарел снимок — сделай выгрузку: meeting.py tasks"])

    # Без отдела (#522) едет признак на месте отдела: публиковать некуда вовсе.
    argv = ["--package", str(package)] + (["--no-team"] if team is None
                                          else ["--team", team])
    if args.dry_run:
        argv.append("--dry-run")
    # Просьба «не публиковать» едет клиенту дословно: у отдела может не быть
    # группы по решению руководителя, и догадаться об этом ни один из двух
    # клиентов не вправе (тикет #280).
    if args.no_publish and team is not None:
        argv.append("--no-publish")
    code = send_package.main(argv)
    if not args.dry_run:
        write_receipt(review, package, team, code)
    return code


def cut_lines(cut) -> list:
    """Пункты, которые сервер отрезал при отправке как устаревшие, — ЕГО СЛОВАМИ (Р15).

    Задачу закрыли, сняли, передали или переименовали после встречи, человека
    выключили: такой пункт не ушёл, а остальное ушло. Слова причины — серверные,
    одни на экран и окно; своих у скрипта нет.
    """
    if not isinstance(cut, list) or not cut:
        return []
    lines = ["Не ушло — сервер отрезал устаревшие пункты:"]
    for one in cut:
        if isinstance(one, dict):
            who = one.get("person_name") or f"id={one.get('person_id')}"
            lines.append(f"  ✂️ пункт {one.get('number')} · {who}: «{one.get('text') or ''}» "
                         f"— {one.get('reason')}")
    return lines


def send_draft(review: Path, env: dict, args, team: str | None, shown: int,
               snapshot: dict | None) -> int:
    """Отправка черновика с сервера (#575, #580): версия последнего показа — дверью
    черновика. Пакет собирает и применяет сервер тем же путём, что пакет из файла.

    Отчёт — тот же, что у двери пакета (`send_package.report_lines`,
    `publication_lines`), и коды те же; сверх него — отрезанные устаревшие пункты
    словами сервера (`cut_lines`). «Не публиковать» едет, только когда его назвали.

    ЧЕРНОВИК ПОПРАВИЛИ ПОСЛЕ ПОКАЗА (`DraftChanged`) — ничего не применено: своя
    копия и сверка заменяются свежим черновиком, подтверждение снимается (слово
    человека относилось к прежнему виду), свежий вид печатается тем же показом,
    что у превью, и модели сказано ждать нового «отправляй» — кодом
    `EXIT_DRAFT_CHANGED`, тем же, что у превью и `confirm`: действие у скилла одно.
    Черновика больше нет — отказ словами сервера (`gone`). Расписка пишется, как у
    любого отказа, — `status` знает, чем кончилась попытка.

    Встречу применённого пакета расписка берёт из ОТЧЁТА СЕРВЕРА (ревью CR-8):
    пакет собирал он, и вид встречи там его (у планёрки отдела — «планёрка»), а не
    тот, что агент вписал в свой файл. По нему досдача итога узнаёт свой отчёт.
    """
    package = review / PACKAGE
    card = meeting_card(review) or {}
    url = client.base_url(env)
    publish = not args.no_publish
    if args.dry_run:
        print(f"Уехала бы отправка черновика разбора, версия {shown}: "
              f"{url}/api/pc/reviews/{card.get('id')}/send"
              + ("" if publish else " — без итога в группе")
              + "\nНичего не отправлено (--dry-run); пакет соберёт и проверит сервер.")
        return client.EXIT_OK
    try:
        body = client.review_draft_send(card.get("id"), draft_job(review), shown,
                                        publish=publish, url=url,
                                        key=client.access_key(env))
        client.check_meetings(body)
    except client.DraftChanged as changed:
        (review / CONFIRMED).unlink(missing_ok=True)
        if changed.fresh is None:
            write_receipt(review, package, team, changed.exit_code)
            raise gone(changed) from None
        write_receipt(review, package, team, EXIT_DRAFT_CHANGED)
        return show_changed(review, read_json(review / DRAFT) or {}, changed.fresh,
                            SEND_CHANGED, snapshot)
    except client.ClientError as beda:
        write_receipt(review, package, team, beda.exit_code)
        raise
    lines = send_package.report_lines(body) + cut_lines(body.get("cut"))
    name = (body.get("team") or {}).get("name") or team or ""
    published, code = send_package.publication_lines(body.get("publication") or {}, name)
    print("\n".join(lines + published))
    write_receipt(review, package, team, code,
                  meeting=(body.get("report") or {}).get("meeting"))
    return code


def cmd_publish(args, env: dict) -> int:
    """Досдача итога в чат отдела. Всегда идёт на сервер — это её работа."""
    review = folder_for(args)
    # У разбора без отдела (#522) итога в группе нет и не будет — досдавать
    # нечего, какой бы отдел ни назвали: сервер его отчёт не опубликует, а чужой
    # последний итог в чат второй раз уезжать не должен.
    if review_without_team(review):
        raise client.Usage(
            "Итога в группе у встречи без отдела нет — досдавать нечего",
            ["разбор без отдела закончен отправкой: задачи в списках, уведомления ушли"])
    team = client.team(args.team)
    # Отдел сверяется с распиской ЭТОГО разбора. Досдача публикует последний
    # применённый пакет НАЗВАННОГО отдела, а не пакет этой папки: назови другой
    # отдел — и в его чат уедет второй раз чужой позавчерашний итог, а здешний
    # так и останется недосданным. Расписки ещё нет (пакет не отправляли) —
    # сверять не с чем, отказ даст сервер.
    receipt = read_json(review / RECEIPT)
    recorded = (receipt or {}).get("team")
    if receipt and not _same_receipt_team(recorded, team):
        raise client.Usage(
            f"Этот разбор сдавали в отдел «{recorded}», а досдаём в «{team}»",
            ["досдача публикует итог названного отдела — чужой чат получил бы "
             "чужую планёрку второй раз",
             f"тот же отдел: meeting.py publish --team \"{recorded}\""])
    package = review / PACKAGE
    argv = ["--publish-only", "--team", team]
    # Своя встреча называется серверу, когда пакет ещё под рукой: досдача
    # публикует последний применённый пакет отдела, а разбор планёрки и разбор
    # 1:1 одного отдела в один день — обычное дело.
    #
    # Пакет, собранный сервером из черновика (`send_draft`), называет ВСТРЕЧА ИЗ
    # ОТЧЁТА СЕРВЕРА, записанная в расписку (ревью CR-8): день и вид там его, а
    # блок `meeting` своего файла вписывал агент — с ним сервер свой отчёт не узнал
    # бы, и досдать было бы нельзя. Вида сервер не назвал — встреча не называется
    # вовсе: сверять её не с чем, досдаётся последний пакет отдела.
    told = (receipt or {}).get("meeting")
    meeting = (told if isinstance(told, dict)
               else (read_json(package) or {}).get("meeting") or {})
    if meeting.get("date") and meeting.get("kind"):
        argv += ["--meeting-date", str(meeting["date"]),
                 "--meeting-kind", str(meeting["kind"])]
    code = send_package.main(argv)
    if package.is_file() and code in (client.EXIT_OK, client.EXIT_PUBLISH_INCOMPLETE):
        write_receipt(review, package, team, code,
                      meeting=told if isinstance(told, dict) else None)
    return code


def cmd_strazh(args, env: dict) -> int:
    """Самопроверка стража слова: вердикт по журналу окна, код 0 или 1.

    Журнал ищется ТАК ЖЕ, как его ищет проверка внутри `confirm` и `send`, — или
    берётся названный. Её позовёт пробный запуск мастера автомата (#516): в
    облаке сообщения человека в окне ещё нет, и ждут там запрет — пропуск значил
    бы, что страж засчитал за человека инструкцию рутины.
    """
    path = Path(args.journal) if args.journal else strazh.find_journal()
    verdict = strazh.judge(path)
    print(f"Журнал: {path}" if path else "Журнал разговора на этой машине не найден.")
    print(f"{'Пропуск' if verdict.allow else 'Запрет'}: {verdict.why}")
    return client.EXIT_OK if verdict.allow else client.EXIT_USAGE


