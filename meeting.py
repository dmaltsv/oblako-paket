# Черновик разбора на сервере (#514; одна запись с экраном разбора — #580)
# ---------------------------------------------------------------------------
def clarification(item) -> bool:
    """Пункт — уточнение: у него есть вопрос `clarify` (правило
    `core._is_review_clarification`)."""
    return isinstance(item, dict) and bool(item.get(CLARIFY))


def _package_item(item):
    """Пункт черновика — пунктом пакета: без ключей черновика (`DRAFT_ONLY_KEYS`),
    у `add` — без пустой цитаты. Правило то же, что у сборки сервером
    (`core._review_package_item`): пакет из файла и пакет, собранный сервером из
    того же черновика, различаться не должны. Пункты, которые не объекты, едут как
    есть — их судит сервер и называет словами."""
    if not isinstance(item, dict):
        return item
    out = {key: value for key, value in item.items() if key not in DRAFT_ONLY_KEYS}
    if out.get("op") == "add" and not (isinstance(out.get("description"), str)
                                       and out["description"].strip()):
        out.pop("description", None)
    return out


def package_of(review: Path, body: dict) -> dict:
    """Пакет из черновика: без уточнений и ключей черновика, С НОМЕРОМ ВСТРЕЧИ из
    карточки и номером задания черновика с сервера.

    Уточнения в пакет не идут (Р4): нерешённое никому не ставится, а решённое
    человек уже сделал обычным пунктом. Цитата `close`/`edit` (`basis`) в задачу не
    уходит, цитата `add` уходит описанием задачи (`_package_item`). Нечего срезать
    и ставить — пакет, как всегда, байт в байт черновик.

    Номер встречи (`meeting.id`, #512) — по нему применение пакета гасит живой
    черновик разбора этой встречи; ставит его скрипт из карточки, а не агент по
    памяти: без номера применённый разбор остался бы на сервере «готов» и звал бы
    человека в чек-ине. Карточки нет — номера нет, и пакет применяется, как всегда.

    НОМЕР ЗАДАНИЯ (`meeting.review_job_id`) — только у черновика с сервера
    (`server_draft_job`): по нему сервер судит, жив ли ещё этот черновик, и пакет
    закрытого разбора — кнопкой «Разбор не нужен», чужим пакетом, «не вышло» —
    не применяет, через какую бы дверь его ни отправили.
    """
    package = dict(body)
    if isinstance(body.get("items"), list):
        package["items"] = [_package_item(item) for item in body["items"]
                            if not clarification(item)]
    number = (meeting_card(review) or {}).get("id")
    if number:
        meeting = package.get("meeting") if isinstance(package.get("meeting"), dict) else {}
        package["meeting"] = {**meeting, "id": number}
        job_id = server_draft_job(review)
        if job_id:
            package["meeting"][REVIEW_JOB_KEY] = job_id
    return package


def no_tasks_words(review: Path, body) -> str | None:
    """Слова «задач нет» у черновика без единого пункта-задачи — иначе None (#521).

    Уточнения (пункты с `clarify`) задачами не считаются и названы числом: из них
    человек словами делает задачи, и тогда разбор перестаёт быть пустым. Кнопку
    «Разбор не нужен» слова называют только у разбора, поставленного автомату
    (`review_ordered`): у ручного разбора на компьютере её нет, и он без задач
    просто закончен. Черновика нет или он не объект — не судим: об этом скажут
    другие шаги.
    """
    if not isinstance(body, dict):
        return None
    items = body.get("items") or []
    if not isinstance(items, list) or any(not clarification(item) for item in items):
        return None
    words = NO_TASKS
    asked = sum(1 for item in items if clarification(item))
    if asked:
        words += NO_TASKS_CLARIFY.format(count=asked)
    return words + (NO_TASKS_BUTTON if review_ordered(meeting_card(review)) else NO_TASKS_DONE)


def review_ordered(card: dict | None) -> bool:
    """Поставлен ли разбор заданию из карточки — есть ли у встречи черновик на сервере.

    Черновик бывает только у задания с разбором (`transcript_review`, `review`):
    у встречи без задания или с одной расшифровкой спрашивать и класть нечего, а
    вопрос стоил бы сети каждому `status`. Карточка старого сервера слова о
    составе работы не несёт — у такого сервера нет и ручек черновика.
    """
    return bool(card and card.get("id") and card.get("job_id")
                and card.get("work") in (avtomat.TRANSCRIPT_REVIEW_WORK, avtomat.REVIEW_WORK))


def server_copy(review: Path) -> dict | None:
    """Последняя сверка черновика с сервером (`package.server.json`) — или None.

    Ключи: `job_id` — задание, которому черновик принадлежит; `version` — версия
    черновика на сервере в минуту сверки; `items` — пункты, какими они были тогда:
    по ним превью узнаёт, правлена ли своя копия с тех пор; `from_server` —
    черновик взят с сервера, а не извлечён здесь; `author` — черновик свой и
    нового поколения, и с ним работают как с одной записью (`shared_draft`).
    """
    copy = read_json(review / SERVER_COPY)
    if not isinstance(copy, dict) or not isinstance(copy.get("items"), list):
        return None
    return copy


def write_server_copy(review: Path, items: list, *, job_id, version, from_server: bool,
                      author: bool) -> None:
    """Записать сверку с сервером. Ключи — у `server_copy`."""
    (review / SERVER_COPY).write_text(json.dumps(
        {"job_id": job_id, "version": version, "items": items, "from_server": from_server,
         "author": author}, ensure_ascii=False, indent=2), encoding="utf-8")


def draft_job(review: Path) -> int | None:
    """Номер задания, которому принадлежит черновик: последней сверки — или карточки.

    Черновик, взятый с сервера, принадлежит СВОЕМУ заданию, и назад он кладётся
    под ним же: у карточки, снятой позже, задание бывает уже новее, и под его
    номером сервер счёл бы положение новым разбором.
    """
    copy = server_copy(review) or {}
    return copy.get("job_id") or (meeting_card(review) or {}).get("job_id")


def signalled_window(review: Path, job_id) -> bool:
    """Черновик кладёт окно СИГНАЛА этого задания — по записи подготовки разбора.

    Запись (`avtomat.RUN_MARK`) пишет `avtomat.py run`, подготовив разбор, и в
    ней сказано, не вечерний ли это проход (#518). Записи нет — на компьютере
    или после перезапуска машины с пустым диском — «не окно сигнала»: письмо
    сервера уйдёт без ссылки, а не со ссылкой на окно чужого запуска.
    """
    mark = read_json(review / avtomat.RUN_MARK)
    return (isinstance(mark, dict) and mark.get("job_id") == job_id
            and mark.get("signalled") is True)


def shared_draft(review: Path) -> bool:
    """Черновик папки — та же запись, что черновик на сервере (Р2, Р16): превью
    сверяется с сервером, `confirm` запоминает версию показа, `send` отправляет её
    дверью черновика.

    Так — у разбора, поставленного заданию из карточки (`review_ordered`): в окне
    всегда (черновик туда кладёт само окно), на компьютере — когда черновик взят с
    сервера, свой и нового поколения (`server_copy`, `author`). Чужой черновик
    (цитаты видит и отправляет только автор разбора, Р9) и черновик необновлённого
    автомата идут как разбор без черновика: пакет из файла старой дверью.
    """
    if not review_ordered(meeting_card(review)):
        return False
    copy = server_copy(review)
    if copy is not None:
        return bool(copy.get("author"))
    return strazh.in_cloud()


def draft_author(draft: dict) -> bool:
    """Черновик сервера — СВОЙ: та же запись, что у экрана (`shared_draft`).

    Свой — это новое поколение (черновик необновлённого автомата и у автора идёт
    старой дверью, Р20) и автор разбора. Автора называет только сервер
    (`draft.author`, судья `core._is_review_author`: исполнитель задания, ещё вправе
    подать пакет) — своего судьи у окна нет. Чужому сервер цитат не отдаст и
    отправить не даст.
    """
    return (draft.get(client.REVIEW_DRAFT_GENERATION) == client.REVIEW_DRAFT_GENERATION_NEW
            and draft.get(client.REVIEW_DRAFT_AUTHOR) is True)


def server_marks(draft: dict | None, key: str) -> list:
    """Слова сервера ПО ПУНКТУ НА ПУНКТ — ключом ``key`` черновика.

    Пометок нет (сервер их не шлёт, черновик не свой) или список не той длины —
    пометок не показываем вовсе, а не приписываем чужие слова чужим пунктам.
    """
    draft = draft if isinstance(draft, dict) else {}
    items = draft.get("items") if isinstance(draft.get("items"), list) else []
    marks = draft.get(key)
    if not isinstance(marks, list) or len(marks) != len(items):
        return [None] * len(items)
    return [mark if isinstance(mark, str) and mark.strip() else None for mark in marks]


def stale_marks(draft: dict | None) -> list:
    """Пометки устаревших пунктов СЛОВАМИ СЕРВЕРА (`draft.stale`) — по пункту на пункт.

    Устаревание судит сервер (`core.review_item_stale`): он же отрежет такой пункт
    при отправке, и экран показывает те же слова.
    """
    return server_marks(draft, client.REVIEW_DRAFT_STALE_MARKS)


def server_notes(draft: dict | None) -> list:
    """Пометки «пункт уйдёт иначе, чем записан» СЛОВАМИ СЕРВЕРА (`draft.notes`, круг 2
    ревью #573, A-1) — по пункту на пункт: рабочий день коллеге из другого отдела не
    уйдёт, ставится только дедлайн. Их считает та же сборка, что отправка; своей
    сверки окно не заводит — второй судья однажды разошёлся бы с первым."""
    return server_marks(draft, client.REVIEW_DRAFT_NOTES)


class DraftGone(client.Refused):
    """Черновика этого задания на сервере больше нет — отправлять отсюда нечего.

    Отдельный вид отказа, чтобы превью не советовало «покажи превью ещё раз»:
    повтор тут ничего не вернёт.
    """


def gone(changed: client.DraftChanged) -> DraftGone:
    """Отказ замка без свежего черновика — СЛОВАМИ СЕРВЕРА (круг 2 ревью, A-9).

    Сервер называет, почему черновика нет: разбор закрыт пакетом другого человека,
    поставлен новый разбор, «Разобрано». Свои слова (`DRAFT_GONE`) — только когда
    сервер причины не назвал.
    """
    words = (changed.reason or "").strip()
    return DraftGone(words or DRAFT_GONE, [GONE_TAIL] if words else [],
                     status=changed.status)


def _adopt(review: Path, body: dict, live: dict, copy: dict | None) -> dict:
    """Черновик сервера — в свою копию и в сверку. Возвращает черновик для показа.

    Меняются только пункты: формат, версия формата и блок `meeting` (вид встречи
    сервер не хранит) остаются своими. Свой ли черновик — по общему правилу
    (`draft_author`), а не «раз пришёл сюда — свой».
    """
    items = live.get("items") if isinstance(live.get("items"), list) else []
    fresh = {**body, "items": items}
    (review / DRAFT).write_text(json.dumps(fresh, ensure_ascii=False, indent=2),
                                encoding="utf-8")
    write_server_copy(review, items, job_id=live.get("job_id"), version=live.get("version"),
                      from_server=bool((copy or {}).get("from_server")),
                      author=draft_author(live))
    return fresh


def show_changed(review: Path, body: dict, live: dict, words: str,
                 snapshot: dict | None) -> int:
    """Черновик поправили на экране после показа — ОДИН ход у `confirm` и `send`:
    подтверждение снято (слово человека относилось к прежнему виду), своя копия и
    сверка заменены свежим черновиком, свежий вид напечатан тем же показом, что у
    превью, и модели сказано ждать нового «отправляй» — кодом `EXIT_DRAFT_CHANGED`.
    """
    (review / CONFIRMED).unlink(missing_ok=True)
    fresh = _adopt(review, body, live, server_copy(review))
    if snapshot is not None:
        show_review(review, fresh, snapshot, DRAFT, judged_by_server=True, server=live)
    print(words.format(version=live.get("version")))
    return EXIT_DRAFT_CHANGED


def sync_draft(review: Path, env: dict, body: dict) -> tuple:
    """СВЕРКА С СЕРВЕРОМ ПЕРЕД ПОКАЗОМ (#580, Р2) — (черновик для показа, слова модели,
    код выхода превью, черновик сервера — источник его слов о пунктах).

    Экран разбора правит ту же запись, и показать человеку свою копию, не
    сверившись, значило бы показать разбор без его правок с экрана. Поэтому:

    1. Своя копия менялась с прошлой сверки (или сверки ещё не было) — правка
       кладётся НОВОЙ ФОРМОЙ: пункты с цитатами и уточнениями в своих ключах (Р3),
       версия, на которой правка основана (`base_version`; первое положение — 0),
       признак окна сигнала. Чисел нет: долю правок считает сервер (Р13).
    2. Черновик тем временем изменился в другом месте (`DraftChanged`) — ничего не
       записано, своя копия заменяется свежей, модели сказано `REAPPLY`, код
       `EXIT_REAPPLY`: правки человека в показанном нет.
    3. Дальше — ЧТЕНИЕ живого черновика: слова сервера о пунктах даёт только оно —
       устаревшие (`stale_marks`) и «уйдёт иначе» (`server_notes`). Версия
       выросла против сверки — это правка экрана: она показывается, модели
       сказано `SCREEN_EDITED`, код `EXIT_DRAFT_CHANGED` —
       «отправляй», сказанное до неё, к свежему виду не относится.

    Черновика этого задания на сервере больше нет (разбор отправили или закрыли на
    экране) — отказ `DraftGone` словами сервера (`gone`), а без них — `DRAFT_GONE`:
    класть его заново сервер всё равно не даст.

    Номер встречи — из КАРТОЧКИ (`Встреча.json`), номер задания — `draft_job`:
    положить черновик вправе исполнитель задания, и сервер сверяет задание со
    встречей. Сверка записывается только после ответа сервера: не лёг черновик —
    сверки не было.
    """
    card = meeting_card(review) or {}
    job_id = draft_job(review)
    if not card.get("id") or not job_id:
        raise client.Usage(
            "У карточки встречи нет задания автомата — черновик разбора класть не к чему",
            [f"карточка: {review / MEETING}",
             "черновик на сервере бывает только у разбора, поставленного автомату"])
    url, key = client.base_url(env), client.access_key(env)
    copy = server_copy(review)
    items = body.get("items") if isinstance(body.get("items"), list) else []
    said = None
    if copy is None or copy["items"] != items:
        try:
            answer = client.review_draft_put(
                card["id"], {"job_id": job_id,
                             client.REVIEW_DRAFT_BASE_VERSION: (copy or {}).get("version") or 0,
                             "items": items, "signalled": signalled_window(review, job_id)},
                url=url, key=key)
        except client.DraftChanged as changed:
            if changed.fresh is None:
                raise gone(changed) from None
            return (_adopt(review, body, changed.fresh, copy),
                    REAPPLY.format(version=changed.fresh.get("version")), EXIT_REAPPLY,
                    changed.fresh)
        client.check_meetings(answer)
        write_server_copy(review, items, job_id=answer.get("job_id") or job_id,
                          version=answer.get("draft_version"),
                          from_server=bool((copy or {}).get("from_server")), author=True)
        said = (f"Черновик разбора на сервере (версия {answer.get('draft_version')}): "
                + (WINDOW_LETTER if signalled_window(review, job_id) else SWEEP_LETTER)
                if answer.get("outcome") == "created" else
                f"Черновик разбора на сервере обновлён: версия {answer.get('draft_version')}.")
        copy = server_copy(review)
    answer = client.review_draft(card["id"], url=url, key=key)
    client.check_review_draft(answer)
    live = answer.get("draft")
    if not isinstance(live, dict) or live.get("job_id") != job_id:
        raise DraftGone(DRAFT_GONE)
    fresh = _adopt(review, body, live, copy)
    if live.get("version") != copy.get("version"):
        edited = SCREEN_EDITED.format(version=live.get("version"))
        return (fresh, f"{said}\n{edited}" if said else edited, EXIT_DRAFT_CHANGED, live)
    return (fresh, said or f"Черновик на сервере — версия {live.get('version')}, правок с "
                           f"экрана нет.", client.EXIT_OK, live)


def restore_draft(review: Path, env: dict) -> str | None:
    """Черновик разбора с сервера — в папку, если своего нет. Слово человеку или None.

    СПРАШИВАЕТ ТОЛЬКО ТАМ, ГДЕ ЕСТЬ ЧТО СПРОСИТЬ: разбор встречи поставлен
    заданию из карточки (`review_ordered`), а ни черновика, ни подтверждённого
    пакета в папке нет. Свой черновик сильнее серверного — с сервером его сверит
    превью.

    ЦИТАТЫ И УТОЧНЕНИЯ ПРИХОДЯТ С ЧЕРНОВИКОМ, ЕСЛИ РАЗБОР СВОЙ (#580, Р3, Р9):
    сервер отдаёт их только автору разбора. Свой черновик нового поколения — та
    же запись, что у экрана (`shared_draft`); чужой или старого поколения (его
    положил необновлённый автомат) приходит без цитат, и разбор идёт, как раньше,
    пакетом из файла. Свой ли он — общее правило `draft_author`: автора называет
    сервер. Вида встречи сервер не хранит — его агент впишет сам.

    СЕРВЕР НЕ ОТВЕТИЛ ИЛИ ОТСТАЛ — ЭТО НЕ ОТКАЗ `status`: разбор идёт как без
    черновика, а причина названа словами. «Где мы?» не вправе падать из-за сети.
    """
    card = meeting_card(review)
    if not review_ordered(card) or (review / DRAFT).is_file() or (review / PACKAGE).is_file():
        return None
    try:
        answer = client.review_draft(card["id"], url=client.base_url(env),
                                     key=client.access_key(env))
        client.check_review_draft(answer)
    except client.ClientError as beda:
        return (f"черновик разбора на сервере не спросить — идём без него: "
                f"{client.redact(beda.message, env.get(client.KEY_ENV))}")
    server_draft = answer.get("draft")
    if not isinstance(server_draft, dict) or not isinstance(server_draft.get("items"), list):
        return None
    items = server_draft["items"]
    restored = {"format": PACKAGE_FORMAT, "version": client.PACKAGE_FORMAT_VERSION,
                "meeting": {"date": card["date"]} if card.get("date") else {},
                "items": items}
    (review / DRAFT).write_text(json.dumps(restored, ensure_ascii=False, indent=2),
                                encoding="utf-8")
    author = draft_author(server_draft)
    write_server_copy(review, items, job_id=server_draft.get("job_id"),
                      version=server_draft.get("version"), from_server=True, author=author)
    return (f"черновик разбора взят с сервера: версия {server_draft.get('version')}, "
            f"пунктов {len(items)}" + ("" if author else " — цитат в нём нет"))


